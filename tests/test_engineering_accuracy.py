def _trapezoidal_volume(flow: tuple[float, ...], timestep_hours: float) -> float:
    return 1800.0 * timestep_hours * math.fsum(previous + current for previous, current in pairwise(flow))


@pytest.mark.parametrize("exponent", [0.6, 0.8, 1.0, 1.3])
def test_independent_stepwise_storage_and_flux_balance(exponent: float) -> None:
    inflow = (0.0, 2.0, 8.0, 3.0, 0.0, 0.0, 0.0)
    coefficient = 0.8
    dt_hours = 0.15
    outflow = route_reach(inflow, coefficient_k=coefficient, exponent_m=exponent, time_step_hours=dt_hours)
    for index, (previous, current) in enumerate(pairwise(outflow), start=1):
        storage_change = storage_volume(current, coefficient_k=coefficient, exponent_m=exponent) - storage_volume(
            previous, coefficient_k=coefficient, exponent_m=exponent
        )
        source_volume = 1800.0 * dt_hours * (inflow[index - 1] + inflow[index])
        outlet_volume = 1800.0 * dt_hours * (previous + current)
        scale_m3 = max(abs(storage_change), source_volume, outlet_volume, 1e-12)
        assert abs(storage_change - (source_volume - outlet_volume)) <= 1e-9 * scale_m3
        assert math.isfinite(current)
        assert current >= 0.0


def test_sub_unit_nonlinear_flow_uses_relative_storage_residual() -> None:
    # Independent bisection benchmark, not a stored output generated by the production solver.
    last_inflow = 1e-20
    dt_hours = 0.25
    target = dt_hours * last_inflow / 2.0
    lower, upper = 0.0, last_inflow
    for _ in range(160):
        middle = (lower + upper) / 2.0
        if middle**0.8 + dt_hours * middle / 2.0 < target:
            lower = middle
        else:
            upper = middle
    expected = (lower + upper) / 2.0
    actual = route_reach((0.0, last_inflow), coefficient_k=1.0, exponent_m=0.8, time_step_hours=dt_hours)
    assert expected > 0.0
    assert actual[-1] == pytest.approx(expected, rel=1e-8, abs=0.0)


def test_exact_linear_continuous_solution_and_second_order_refinement() -> None:
    # For dQ/dt=(I-Q)/k, I(t)=a+b exp(-lambda*t), Q(0)=I(0), the integral is explicit.
    a, b, decay, coefficient, end_hour = 2.0, 3.0, 0.3, 1.0, 4.0
    exact = a + b * (math.exp(-decay * end_hour) - coefficient * decay * math.exp(-end_hour / coefficient)) / (
        1.0 - coefficient * decay
    )
    errors: list[float] = []
    for dt_hours in (0.5, 0.25, 0.125):
        steps = round(end_hour / dt_hours)
        inflow = tuple(a + b * math.exp(-decay * step * dt_hours) for step in range(steps + 1))
        routed = route_reach(inflow, coefficient_k=coefficient, exponent_m=1.0, time_step_hours=dt_hours)
        errors.append(abs(routed[-1] - exact))
    assert errors[0] < 0.002
    assert errors[1] < 0.3 * errors[0]
    assert errors[2] < 0.3 * errors[1]


def test_independent_nonlinear_manufactured_refinement() -> None:
    # Q(t)=2+0.04*t²; I(t)=Q(t)+d[k*Q(t)^m]/dt is a continuous exact solution.
    exponent, coefficient, end_hour = 0.8, 1.0, 4.0

    def expected_flow(hour: float) -> float:
        return 2.0 + 0.04 * hour * hour

    def manufactured_inflow(hour: float) -> float:
        discharge = expected_flow(hour)
        return discharge + coefficient * exponent * discharge ** (exponent - 1.0) * 0.08 * hour

    errors: list[float] = []
    for dt_hours in (0.5, 0.25, 0.125):
        count = round(end_hour / dt_hours)
        inflow = tuple(manufactured_inflow(index * dt_hours) for index in range(count + 1))
        routed = route_reach(inflow, coefficient_k=coefficient, exponent_m=exponent, time_step_hours=dt_hours)
        errors.append(abs(routed[-1] - expected_flow(end_hour)))
    assert errors[0] < 1e-4
    assert errors[1] < 0.3 * errors[0]
    assert errors[2] < 0.3 * errors[1]


def test_within_bin_loss_crossing_equality_and_dry_carry() -> None:
    losses = Losses(initial_mm=5.0, continuing_mm_h=2.0)
    assert rainfall_excess((10.0,), losses=losses, timestep_hours=1.0) == pytest.approx((4.0,))
    assert rainfall_excess((5.0, 10.0), losses=losses, timestep_hours=1.0) == (0.0, 8.0)
    assert rainfall_excess((3.0, 0.0, 2.0, 10.0), losses=losses, timestep_hours=1.0) == (
        0.0,
        0.0,
        0.0,
        8.0,
    )
    assert rainfall_excess((10.0,), losses=Losses(0.0, 2.0), timestep_hours=1.0) == (8.0,)


def test_branched_network_mass_accounts_for_remaining_reach_storage() -> None:
    catchment = Catchment(
        (Control(1, 2.0), Control(3), Control(1, 4.0), Control(4), Control(5, 3.0), Control(7)),
        (1.0, 3.0),
    )
    storm = Storm(0.1, 120, (40.0, 60.0), (5.0, 7.0))
    coefficient = 0.4
    result = calculate_storm(catchment, storm, losses=Losses(0.0, 0.0), kc=coefficient, m=1.0)
    dt_hours = storm.timestep_hours
    branch_a = route_reach(
        result.source_hydrographs_m3_s[0],
        coefficient_k=coefficient * result.route_factors[0],
        exponent_m=1.0,
        time_step_hours=dt_hours,
    )
    branch_b = route_reach(
        result.source_hydrographs_m3_s[1],
        coefficient_k=coefficient * result.route_factors[1],
        exponent_m=1.0,
        time_step_hours=dt_hours,
    )
    junction = tuple(a + b for a, b in zip(branch_a, branch_b, strict=True))
    final = route_reach(
        junction, coefficient_k=coefficient * result.route_factors[2], exponent_m=1.0, time_step_hours=dt_hours
    )
    assert result.outlets_m3_s == (final,)
    source_volume = math.fsum(_trapezoidal_volume(series, dt_hours) for series in result.source_hydrographs_m3_s)
    outlet_volume = _trapezoidal_volume(final, dt_hours)
    stored = math.fsum(
        storage_volume(series[-1], coefficient_k=coefficient * factor, exponent_m=1.0)
        for series, factor in zip((branch_a, branch_b, final), result.route_factors, strict=True)
    )
    assert source_volume - outlet_volume == pytest.approx(stored, rel=1e-9, abs=1e-7)
    # This event has a padded zero-source recession; storage tends to zero,
    # rather than being silently discarded at the computation horizon.
    assert stored < 1e-5
    assert len(final) == storm.calculation_increments + 1


def test_single_zero_length_reach_is_an_explicit_no_storage_branch() -> None:
    catchment = Catchment(
        (Control(1, 0.0), Control(3), Control(1, 4.0), Control(4), Control(7)),
        (1.0, 1.0),
    )
    distance, factors = distance_analysis(catchment)
    assert distance == 2.0
    assert factors == (0.0, 2.0)
    event = Storm(0.1, 20, (100.0,), (3.6, 3.6))
    result = calculate_storm(catchment, event, losses=Losses(0.0, 0.0), kc=1.0, m=1.0)
    assert len(result.outlets_m3_s[0]) == event.calculation_increments + 1
    assert result.outlets_m3_s[0][1] > 0.0


